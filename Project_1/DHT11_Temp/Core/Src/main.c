void motor_config(void) {
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_3, GPIO_PIN_SET); //STBY
	HAL_GPIO_WritePin(GPIOC, GPIO_PIN_0, GPIO_PIN_SET); //AIN1
	HAL_GPIO_WritePin(GPIOC, GPIO_PIN_1, GPIO_PIN_RESET); //AIN2

	HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);

	__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 300);
}

void speed_monitoring(void) {

	if (DHT11_GetData(GPIOA, GPIO_PIN_2, &dht)) {
		// Use dht.Temperature and dht.Humidity
		lprint(0x80, "Tem:");
		aprint(0x86, dht.Temperature);
		lprint(0xC0, "hum:");
		aprint(0xC6, dht.Humidity);

		if (dht.Temperature >= 27 && dht.Humidity >= 73 && flag != 1) {
			lprint(0x80, "Temperature exceeded");
			// Gradual motor slowdown using PWM
			uint16_t pwm_values[] = { 600, 400, 200, 0 };
			for (int i = 0; i < 4; i++) {
				__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pwm_values[i]);
				HAL_Delay(2000);
			}
			flag = 1;
		}

		if (vibrationDetected) {
			lprint(0x80, "High Vibration Detected");

			if (flag != 1) {
				// Gradual motor slowdown using PWM
				uint16_t pwm_values[] = { 600, 400, 200, 0 };
				for (int i = 0; i < 4; i++) {
					__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pwm_values[i]);
					HAL_Delay(2000);
				}
				flag = 1;
			}

			vibrationDetected = 0;
		}

		else if (dht.Temperature <= 26 && dht.Humidity >= 65 && flag == 1
				&& vibrationDetected == 0) {
			flag = 0;
			__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 300);
			//HAL_Delay(2000);

		}
	}

}

void safety_monitoring(void) {
	pir_status = HAL_GPIO_ReadPin(GPIOB, GPIO_PIN_6);

	if (pir_status) {
		// Motion detected
		lprint(0x80, "Motion Detected");
		HAL_GPIO_WritePin(GPIOC, GPIO_PIN_6, GPIO_PIN_RESET); // LED ON
		//HAL_GPIO_WritePin(GPIOC, GPIO_PIN_9, GPIO_PIN_SET); // BUZZER ON
		lprint(0xC8, "PIR:1");

	} else {
		lprint(0xC8, "PIR:0");
		HAL_GPIO_WritePin(GPIOC, GPIO_PIN_6, GPIO_PIN_SET);   // LED OFF
		//HAL_GPIO_WritePin(GPIOC, GPIO_PIN_9, GPIO_PIN_RESET); // BUZZER OFF
	}

}

